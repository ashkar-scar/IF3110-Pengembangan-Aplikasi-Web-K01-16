func TestAdminEditAndSQLiteRegistry(t *testing.T) {
	f := backendA(t)
	admin := f.login(t, "admin")
	u := f.users["viewer"]
	body := fmt.Sprintf(`{"username":"viewer-renamed","is_active":false,"is_platform_admin":false}`)
	decode(t, f.request("PUT", fmt.Sprintf("/api/admin/users/%d", u.ID), body, admin), 200, nil)
	decode(t, f.request("POST", "/api/auth/login", `{"username":"viewer-renamed","password":"testing-password"}`, credentials{}), 401, nil)
	var g core.Group
	decode(t, f.request("POST", "/api/admin/groups", `{"name":"rename-me"}`, admin), 201, &g)
	path := fmt.Sprintf("/api/admin/groups/%d", g.ID)
	decode(t, f.request("PUT", path, `{"name":"renamed"}`, admin), 204, nil)
	decode(t, f.request("DELETE", path, "", admin), 204, nil)
	var target core.DatabaseTarget
	decode(t, f.request("POST", "/api/admin/databases", `{"name":"SQLite test","driver":"sqlite","database":"../../outside.db"}`, admin), 201, &target)
	if !strings.HasSuffix(target.Database, ".db") || strings.Contains(target.Database, "/") {
		t.Fatal("SQLite file must be generated by server", target.Database)
	}
	record, err := f.api.registry.FindByID(context.Background(), target.ID)
	if err != nil {
		t.Fatal(err)
	}
	conn, err := f.api.open(context.Background(), asTarget(record, core.PermissionEdit))
	if err != nil {
		t.Fatal(err)
	}
	conn.Close()
}

func TestSchemaDiffPagePermissionsAndDraft(t *testing.T) {
	f := backendA(t)
	admin := f.login(t, "admin")
	var first, second core.DatabaseTarget
	for i, record := range []*core.DatabaseTarget{&first, &second} {
		decode(t, f.request("POST", "/api/admin/databases", fmt.Sprintf(`{"name":"diff-%d","driver":"sqlite"}`, i), admin), 201, record)
	}
	for _, record := range []core.DatabaseTarget{first, second} {
		r, _ := f.api.registry.FindByID(context.Background(), record.ID)
		conn, err := f.api.open(context.Background(), asTarget(r, core.PermissionEdit))
		if err != nil {
			t.Fatal(err)
		}
		if record.ID == second.ID {
			_, err = conn.DB.Exec("CREATE TABLE example(id INTEGER PRIMARY KEY)")
			if err != nil {
				t.Fatal(err)
			}
		}
		conn.Close()
	}
	var group core.Group
	decode(t, f.request("POST", "/api/admin/groups", `{"name":"diff-editors"}`, admin), 201, &group)
	decode(t, f.request("POST", fmt.Sprintf("/api/admin/groups/%d/members", group.ID), fmt.Sprintf(`{"user_id":%d}`, f.users["editor"].ID), admin), 204, nil)
	for _, record := range []core.DatabaseTarget{first, second} {
		decode(t, f.request("PUT", fmt.Sprintf("/api/admin/groups/%d/grants/%d", group.ID, record.ID), `{"permission":"EDIT"}`, admin), 204, nil)
	}
	editor := f.login(t, "editor")
	viewer := f.login(t, "viewer")
	path := fmt.Sprintf("/databases/%d/diff", first.ID)
	decode(t, f.request("GET", path, "", viewer), 403, nil)
	decode(t, f.request("GET", path, "", editor), 200, nil)
	values := url.Values{"csrf_token": {editor.csrf}, "source_id": {fmt.Sprint(second.ID)}, "current_schema": {"main"}, "desired_schema": {"main"}, "action": {"draft"}}
	r := httptest.NewRequest("POST", path, strings.NewReader(values.Encode()))
	r.Header.Set("Content-Type", "application/x-www-form-urlencoded")
	r.AddCookie(editor.cookie)
	w := httptest.NewRecorder()
	f.router.ServeHTTP(w, r)
	if w.Code != 303 || !strings.Contains(w.Header().Get("Location"), "draft=") {
		t.Fatal(w.Code, w.Body.String())
	}
	drafts, err := f.api.migrations.ListDrafts(context.Background(), first.ID)
	if err != nil || len(drafts) != 1 || !strings.Contains(drafts[0].SQL, "CREATE TABLE") || drafts[0].Fingerprint == "" {
		t.Fatal(drafts, err)
	}
}
